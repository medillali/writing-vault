  const graphBox=await m.locator('#graph-viewport').boundingBox(),before=await m.locator('#graph-scale').innerText();
  const cdp=await mobile.newCDPSession(m),cx=graphBox.x+graphBox.width/2,cy=graphBox.y+graphBox.height/2;
